import SwiftUI

public enum ShibaAnimationState: String, CaseIterable, Identifiable {
    case idle = "Idle", converting = "Converting", completed = "Completed", failed = "Failed"
    public var id: String { rawValue }
}

public struct ShibaPixelView: View {
    public var state: ShibaAnimationState
    public var pixelSize: CGFloat = 5
    @Environment(\.accessibilityReduceMotion) private var reduceMotion

    public init(state: ShibaAnimationState, pixelSize: CGFloat = 5) {
        self.state = state
        self.pixelSize = pixelSize
    }

    public var body: some View {
        Group {
            if reduceMotion {
                sprite(frame: 0)
            } else {
                TimelineView(.periodic(from: .now, by: interval)) { timeline in
                    sprite(frame: Int(timeline.date.timeIntervalSinceReferenceDate / interval) % 8)
                }
            }
        }
        .frame(width: 16 * pixelSize, height: 16 * pixelSize)
        .accessibilityElement(children: .ignore)
        .accessibilityLabel(description)
    }

    private var interval: TimeInterval {
        switch state {
        case .idle: return 0.36
        case .converting: return 0.14
        case .completed: return 0.24
        case .failed: return 0.40
        }
    }

    private var description: String {
        switch state {
        case .idle: return "柴犬待機中"
        case .converting: return "柴犬轉檔中"
        case .completed: return "轉檔完成"
        case .failed: return "轉檔失敗或警告"
        }
    }

    private func sprite(frame: Int) -> some View {
        Canvas { context, size in
            let rows = Self.frames[state]![frame]
            // Keep the original component footprint used by both header and empty state.
            let unit = min(size.width, size.height) / 40
            for (y, row) in rows.enumerated() {
                for (x, code) in row.enumerated() {
                    guard let color = Self.palette[code] else { continue }
                    let rect = CGRect(x: CGFloat(x) * unit, y: CGFloat(y) * unit,
                                      width: unit, height: unit)
                    context.fill(Path(rect), with: .color(color))
                }
            }
        }
    }

